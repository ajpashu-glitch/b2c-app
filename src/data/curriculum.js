export function getSubject(id) {
  return SUBJECTS.find((s) => s.id === id)
}

export function getSkills(subjectId, gradeId) {
  const bespoke = SKILLS[subjectId]?.[gradeId]
  return bespoke ?? FALLBACK[subjectId] ?? []
}

export function gradesForSubject(subjectId) {
  const subject = getSubject(subjectId)
  if (!subject) return GRADES
  return GRADES.filter((g) => subject.grades.includes(g.id))
}

